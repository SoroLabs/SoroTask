#!/usr/bin/env node
'use strict';

/**
 * generate-soroban-verifier.js (#1209)
 *
 * Reads a snarkjs Groth16 verification key JSON (as exported by
 * `snarkjs zkey export verificationkey`) and generates a self-contained Rust
 * crate that implements a native Soroban verifier contract for it:
 *
 *   - the Groth16 verifying-key constants (alpha, beta, gamma, delta, IC)
 *     are embedded as decimal-string constants,
 *   - the contract exposes `verify_proof(...)`, which rebuilds the
 *     arkworks/bn254 key and delegates to `ark_groth16::verify_proof`,
 *   - an automated Rust test parses every constant and exercises the
 *     verification entry point,
 *
 * `cargo build --release --target wasm32-unknown-unknown` on the generated
 * crate produces the deployable `soroban_zk_verifier.wasm`.
 *
 * Usage: node generate-soroban-verifier.js <verification_key.json> <output_dir>
 */

const fs = require('node:fs');
const path = require('node:path');

function readVerifyingKey(vkeyPath) {
  const raw = fs.readFileSync(vkeyPath, 'utf8');
  const vkey = JSON.parse(raw);
  if (vkey.protocol !== 'groth16') {
    throw new Error(`Unsupported protocol '${vkey.protocol}' — only groth16 is supported`);
  }
  if (vkey.curve !== 'bn128' && vkey.curve !== 'bn254') {
    throw new Error(`Unsupported curve '${vkey.curve}' — only bn128/bn254 is supported`);
  }
  for (const field of ['vk_alpha_1', 'vk_beta_2', 'vk_gamma_2', 'vk_delta_2', 'IC']) {
    if (!Array.isArray(vkey[field])) {
      throw new Error(`Verification key is missing '${field}'`);
    }
  }
  if (!Number.isInteger(vkey.nPublic) || vkey.nPublic < 0) {
    throw new Error(`Verification key has invalid nPublic: ${vkey.nPublic}`);
  }
  if (vkey.IC.length !== vkey.nPublic + 1) {
    throw new Error(
      `IC has ${vkey.IC.length} elements but nPublic + 1 = ${vkey.nPublic + 1}`
    );
  }
  return vkey;
}

/** G1 points in snarkjs JSON are [x, y, "1"] decimal strings. */
function g1RustLiteral(g1, label) {
  const [x, y] = g1;
  assertDecimal(x, `${label}.x`);
  assertDecimal(y, `${label}.y`);
  return `G1Affine::new(Fq::from_str("${x}").expect("invalid ${label}.x"), Fq::from_str("${y}").expect("invalid ${label}.y"), false)`;
}

/**
 * G2 points in snarkjs JSON are [[x_c1, x_c0], [y_c1, y_c0], ["1","1"]].
 * snarkjs lists Fq2 coordinates in REVERSED order relative to arkworks
 * (arkworks Fq2::new(c0, c1)), so the generator swaps them here.
 */
function g2RustLiteral(g2, label) {
  const [x, y] = g2;
  const [x1, x0] = x;
  const [y1, y0] = y;
  for (const [value, name] of [[x0, `${label}.x.c0`], [x1, `${label}.x.c1`], [y0, `${label}.y.c0`], [y1, `${label}.y.c1`]]) {
    assertDecimal(value, name);
  }
  return [
    'G2Affine::new(',
    `    Fq2::new(Fq::from_str("${x0}").expect("invalid ${label}.x.c0"), Fq::from_str("${x1}").expect("invalid ${label}.x.c1")),`,
    `    Fq2::new(Fq::from_str("${y0}").expect("invalid ${label}.y.c0"), Fq::from_str("${y1}").expect("invalid ${label}.y.c1")),`,
    '    false,',
    ')',
  ].join('\n');
}

function assertDecimal(value, label) {
  if (typeof value !== 'string' || !/^\d+$/.test(value)) {
    throw new Error(`${label} is not a decimal string: ${JSON.stringify(value)}`);
  }
}

function icRustLiterals(ic) {
  return ic.map((point, index) => `        ${g1RustLiteral(point, `IC[${index}]`)},`).join('\n');
}

function generateLibRs(vkey) {
  const alpha = g1RustLiteral(vkey.vk_alpha_1, 'vk_alpha_1');
  const beta = g2RustLiteral(vkey.vk_beta_2, 'vk_beta_2');
  const gamma = g2RustLiteral(vkey.vk_gamma_2, 'vk_gamma_2');
  const delta = g2RustLiteral(vkey.vk_delta_2, 'vk_delta_2');
  const ic = icRustLiterals(vkey.IC);

  return `//! Auto-generated Soroban Groth16 verifier (#1209).
//!
//! Generated by \`scripts/generate-soroban-verifier.js\` from a snarkjs
//! verification key. Do not edit by hand — regenerate instead.
//!
//! Layout: the Groth16 verifying-key constants are embedded as decimal
//! strings, parsed into arkworks/bn254 group elements on first use, and fed
//! into \`ark_groth16::verify_proof\`. snarkjs lists G2 coordinates in reversed
//! Fq2 order; the conversion is applied in \`g2_from_snarkjs\`.

use ark_bn254::{Bn254, Fq, Fq2, Fr, G1Affine, G2Affine};
use ark_groth16::{prepare_verifying_key, verify_proof, Proof, VerifyingKey};
use soroban_sdk::{contract, contractimpl, vec, Env, Vec};

/// Number of public input signals the circuit expects.
pub const N_PUBLIC: usize = ${vkey.nPublic};

/// Embedded verifying-key constants (decimal strings, schema v1).
pub const VK_ALPHA_1: (&str, &str) = (${JSON.stringify(String(vkey.vk_alpha_1[0]))}, ${JSON.stringify(String(vkey.vk_alpha_1[1]))});
pub const VK_BETA_2: (&str, &str, &str, &str) = (${JSON.stringify(String(vkey.vk_beta_2[0][0]))}, ${JSON.stringify(String(vkey.vk_beta_2[0][1]))}, ${JSON.stringify(String(vkey.vk_beta_2[1][0]))}, ${JSON.stringify(String(vkey.vk_beta_2[1][1]))});
pub const VK_GAMMA_2: (&str, &str, &str, &str) = (${JSON.stringify(String(vkey.vk_gamma_2[0][0]))}, ${JSON.stringify(String(vkey.vk_gamma_2[0][1]))}, ${JSON.stringify(String(vkey.vk_gamma_2[1][0]))}, ${JSON.stringify(String(vkey.vk_gamma_2[1][1]))});
pub const VK_DELTA_2: (&str, &str, &str, &str) = (${JSON.stringify(String(vkey.vk_delta_2[0][0]))}, ${JSON.stringify(String(vkey.vk_delta_2[0][1]))}, ${JSON.stringify(String(vkey.vk_delta_2[1][0]))}, ${JSON.stringify(String(vkey.vk_delta_2[1][1]))});
pub const IC: [(&str, &str); ${vkey.IC.length}] = [
${vkey.IC.map((p) => `    (${JSON.stringify(String(p[0]))}, ${JSON.stringify(String(p[1]))}),`).join('\n')}
];

fn fq(value: &str) -> Fq {
    value.parse::<Fq>().expect("invalid bn254 Fq constant")
}

/// Builds the arkworks verifying key from the embedded constants.
fn verifying_key() -> VerifyingKey<Bn254> {
    VerifyingKey::<Bn254> {
        alpha_g1: G1Affine::new(fq(VK_ALPHA_1.0), fq(VK_ALPHA_1.1), false),
        beta_g2: g2_from_snarkjs(VK_BETA_2),
        gamma_g2: g2_from_snarkjs(VK_GAMMA_2),
        delta_g2: g2_from_snarkjs(VK_DELTA_2),
        ic: IC
            .iter()
            .map(|(x, y)| G1Affine::new(fq(x), fq(y), false))
            .collect(),
    }
}

/// Converts a snarkjs-format G2 tuple \`(x_c1, x_c0, y_c1, y_c0)\` into an
/// arkworks G2 affine point (snarkjs reverses the Fq2 coordinate order).
fn g2_from_snarkjs(coords: (&str, &str, &str, &str)) -> G2Affine {
    let (x_c1, x_c0, y_c1, y_c0) = coords;
    G2Affine::new(
        Fq2::new(fq(x_c0), fq(x_c1)),
        Fq2::new(fq(y_c0), fq(y_c1)),
        false,
    )
}

fn g1_from_snarkjs(x: &str, y: &str) -> Result<G1Affine, String> {
    let px = x.parse::<Fq>().map_err(|_| "invalid G1 x coordinate".to_string())?;
    let py = y.parse::<Fq>().map_err(|_| "invalid G1 y coordinate".to_string())?;
    Ok(G1Affine::new(px, py, false))
}

fn g2_from_proof(coords: (&str, &str, &str, &str)) -> Result<G2Affine, String> {
    let (x_c1, x_c0, y_c1, y_c0) = coords;
    let x = Fq2::new(
        x_c0.parse::<Fq>().map_err(|_| "invalid G2 x.c0".to_string())?,
        x_c1.parse::<Fq>().map_err(|_| "invalid G2 x.c1".to_string())?,
    );
    let y = Fq2::new(
        y_c0.parse::<Fq>().map_err(|_| "invalid G2 y.c0".to_string())?,
        y_c1.parse::<Fq>().map_err(|_| "invalid G2 y.c1".to_string())?,
    );
    Ok(G2Affine::new(x, y, false))
}

#[contract]
pub struct SorobanZkVerifier;

#[contractimpl]
impl SorobanZkVerifier {
    /// Number of public inputs expected by the embedded verifying key.
    pub fn n_public() -> u32 {
        N_PUBLIC as u32
    }

    /// Verifies a Groth16 proof against the embedded verifying key.
    ///
    /// \`proof\` is a flat vector in snarkjs wire order:
    /// \`[pi_a.x, pi_a.y, pi_b.x.c1, pi_b.x.c0, pi_b.y.c1, pi_b.y.c0, pi_c.x, pi_c.y]\`
    /// (G2 coordinates in snarkjs' reversed Fq2 order), followed by the
    /// public input values as decimal strings.
    pub fn verify_proof(env: Env, proof: Vec<soroban_sdk::String>) -> bool {
        if proof.len() < 8 {
            return false;
        }
        let text = |index: u32| -> String {
            proof
                .get(index)
                .unwrap_or_else(|| soroban_sdk::String::from_str(&env, ""))
        };

        let pi_a = match g1_from_snarkjs(&text(0), &text(1)) {
            Ok(point) => point,
            Err(_) => return false,
        };
        let pi_b = match g2_from_proof((&text(2), &text(3), &text(4), &text(5))) {
            Ok(point) => point,
            Err(_) => return false,
        };
        let pi_c = match g1_from_snarkjs(&text(6), &text(7)) {
            Ok(point) => point,
            Err(_) => return false,
        };

        let mut public_inputs: ::std::vec::Vec<Fr> = ::std::vec::Vec::with_capacity(N_PUBLIC);
        for index in 8u32..proof.len() {
            let bytes = text(index).to_bytes().to_alloc();
            let text_value = match ::std::str::from_utf8(&bytes) {
                Ok(value) => value,
                Err(_) => return false,
            };
            match text_value.parse::<Fr>() {
                Ok(value) => public_inputs.push(value),
                Err(_) => return false,
            }
        }
        if public_inputs.len() != N_PUBLIC {
            return false;
        }

        let pvk = prepare_verifying_key(&verifying_key());
        let proof = Proof::<Bn254> {
            a: pi_a,
            b: pi_b,
            c: pi_c,
        };

        verify_proof(&pvk, &proof, &public_inputs).unwrap_or(false)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every embedded constant must parse into its field/group element.
    #[test]
    fn embedded_constants_parse() {
        let vk = verifying_key();
        assert!(!vk.alpha_g1.infinity);
        assert!(!vk.beta_g2.infinity);
        assert!(!vk.gamma_g2.infinity);
        assert!(!vk.delta_g2.infinity);
        assert_eq!(vk.ic.len(), N_PUBLIC + 1);
        for point in &vk.ic {
            assert!(!point.infinity);
        }
    }

    /// The generated verifier must reject malformed proofs instead of panicking.
    #[test]
    fn verify_proof_rejects_malformed_input() {
        let env = Env::default();
        let short = vec![&env];
        assert!(!SorobanZkVerifier::verify_proof(env.clone(), short));

        let garbage = vec![
            &env,
            soroban_sdk::String::from_str(&env, "0"),
            soroban_sdk::String::from_str(&env, "0"),
            soroban_sdk::String::from_str(&env, "0"),
            soroban_sdk::String::from_str(&env, "0"),
            soroban_sdk::String::from_str(&env, "0"),
            soroban_sdk::String::from_str(&env, "0"),
            soroban_sdk::String::from_str(&env, "0"),
            soroban_sdk::String::from_str(&env, "0"),
        ];
        assert!(!SorobanZkVerifier::verify_proof(env, garbage));
    }

    /// Public-input count must match the circuit exactly.
    #[test]
    fn verify_proof_enforces_public_input_count() {
        let env = Env::default();
        let mut flat: Vec<soroban_sdk::String> = vec![&env];
        for _ in 0..8u32 {
            flat.push_back(soroban_sdk::String::from_str(&env, "0"));
        }
        // One extra "public input" -> mismatch with N_PUBLIC -> false.
        for _ in 0..(N_PUBLIC as u32 + 1) {
            flat.push_back(soroban_sdk::String::from_str(&env, "1"));
        }
        assert!(!SorobanZkVerifier::verify_proof(env, flat));
    }
}
`;
}

function main() {
  const [vkeyPath, outDir] = process.argv.slice(2);
  if (!vkeyPath || !outDir) {
    console.error('Usage: node generate-soroban-verifier.js <verification_key.json> <output_dir>');
    process.exit(1);
  }

  const vkey = readVerifyingKey(vkeyPath);
  fs.mkdirSync(path.join(outDir, 'src'), { recursive: true });

  fs.writeFileSync(
    path.join(outDir, 'Cargo.toml'),
    `[package]
name = "soroban-zk-verifier"
version = "0.1.0"
edition = "2021"
publish = false
description = "Auto-generated Soroban Groth16 verifier contract (#1209)"

[lib]
crate-type = ["cdylib", "rlib"]

[dependencies]
soroban-sdk = "22.0.11"
ark-bn254 = { version = "0.4", default-features = false, features = ["curve"] }
ark-ec = { version = "0.4", default-features = false }
ark-ff = { version = "0.4", default-features = false }
ark-groth16 = { version = "0.4", default-features = false }
ark-serialize = { version = "0.4", default-features = false }
`
  );

  fs.writeFileSync(path.join(outDir, 'src', 'lib.rs'), generateLibRs(vkey));
  console.log(
    `Generated Soroban verifier crate at ${outDir} (nPublic=${vkey.nPublic}, IC=${vkey.IC.length}).`
  );
}

if (require.main === module) {
  main();
}

module.exports = { readVerifyingKey, generateLibRs, g2RustLiteral };
